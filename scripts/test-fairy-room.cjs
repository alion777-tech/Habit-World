const near = (actual, expected) => assert.ok(Math.abs(actual - expected) < 1e-8, `${actual} != ${expected}`);
assert.equal(initial.energy, 100);
assert.equal(advanceRoom(initial, now + day / 2).health, 100);
near(advanceRoom(initial, now + day / 2).energy, 100 - 100 / 14);
assert.equal(advanceRoom(initial, now - day).health, 100);
assert.equal(advanceRoom(initial, now - day).updatedAt, now);
assert.equal(initial.records.length, 2, 'projection never mutates its source');
assert.ok(Math.abs(heartFill(73, 3) - .65) < 1e-10);
assert.equal(heartFill(73, 4), 0);
assert.equal(heartFill(100, 4), 1);
near(advanceRoom(initial, now + 7 * day).health, 50);
assert.equal(advanceRoom(initial, now + 7 * day).energy, 0);
assert.equal(advanceRoom(initial, now + 7 * day).sleeping, false, 'zero energy alone does not cause sleep');
const threshold = advanceRoom(initial, now + 10.15 * day);
