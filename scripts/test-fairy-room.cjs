const assert = require('node:assert/strict');
const fs = require('node:fs');
const ts = require('typescript');
const vm = require('node:vm');
const loader=require('./load-model.cjs');
const context = { exports: loader.load('../lib/fairyRoomModel.ts') };loader.restore();
const { createRoom, advanceRoom, recoverFromHabit, departAdventure, heartFill, ROOM_RULES } = context.exports;
const now = Date.parse('2026-09-12T03:00:00Z'), day = 86400000;
const initial = createRoom(now, '2026-09-12');
assert.equal(initial.health, 100);
assert.equal(advanceRoom(initial, now + day / 2).health, 97.5);
assert.equal(advanceRoom(initial, now - day).health, 100);
assert.equal(advanceRoom(initial, now - day).updatedAt, now);
assert.equal(initial.records.length, 2, 'projection never mutates its source');
assert.ok(Math.abs(heartFill(73, 3) - .65) < 1e-10);
assert.equal(heartFill(73, 4), 0);
assert.equal(heartFill(100, 4), 1);
const asleep = advanceRoom(initial, now + 21 * day);
assert.equal(asleep.health, 0); assert.equal(asleep.sleeping, true);
assert.equal(advanceRoom(asleep, now + 22 * day).records.length, asleep.records.length);
const awake = recoverFromHabit(asleep, now + 21 * day, '2026-10-03', 'habit-a');
assert.equal(awake.health, 8); assert.equal(awake.sleeping, false);
assert.equal(recoverFromHabit(awake, now + 21 * day, '2026-10-03', 'habit-a').health, 8);
assert.equal(recoverFromHabit(awake, now + 21 * day, '2026-10-03', 'habit-b').health, 16);
assert.equal(recoverFromHabit(awake, now + 22 * day, '2026-10-04', 'habit-a').health, 11);
assert.equal(recoverFromHabit(initial, now, '2026-09-12', 'habit-a').health, 100);
assert.throws(() => departAdventure({ ...initial, health: 79.99 }, now, 'forest', .5));
assert.throws(() => departAdventure(initial, now, 'lake', .5));
const trip = departAdventure({ ...initial, health: 80 }, now, 'forest', .5);
assert.equal(trip.health, 60); assert.equal(trip.adventure.reward, 30);
assert.throws(() => departAdventure(trip, now, 'forest', .1));
assert.equal(advanceRoom(trip, now + day - 1).adventurePoints, 0);
const returned = advanceRoom(trip, now + day);
assert.equal(returned.adventure, null); assert.equal(returned.adventurePoints, 30);
assert.equal(returned.health, 55);
assert.equal(advanceRoom(returned, now + day).adventurePoints, 30);
assert.equal(departAdventure(initial, now, 'forest', 0).adventure.reward, 20);
assert.equal(departAdventure(initial, now, 'forest', 1).adventure.reward, 40);
let grown = initial;
for (let level = 2; level < 120; level++) grown = advanceRoom(grown, now, level);
assert.equal(grown.records.length, ROOM_RULES.recordLimit);
assert.equal(advanceRoom(grown, now, 2).highestLevel, 119);
assert.equal(advanceRoom(grown, now, 119).records.length, 100);
console.log('Fairy room: decay, sleep/wake, daily recovery, partial hearts, departure boundaries, single rewards and record cap passed.');
